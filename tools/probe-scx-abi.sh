#!/usr/bin/env bash
# Probe how the scx headers in SCX_INC differ from what the scheduler sources assume,
# and print a header (conductor_probe.h) with the resulting -D choices.
#
#   probe-scx-abi.sh <clang> <arch: x86|arm64> <vmlinux-dir> <scx-inc> [extra -I dirs...] > conductor_probe.h
#
# Currently probes one thing: whether scx_bpf_dsq_move_to_local() takes 2 arguments
# (newer headers) or 1 (older). Exit status is 0 even if a probe fails to compile
# for unrelated reasons; the corresponding define is then simply left unset.
set -u
CLANG=${1:?clang}; ARCH=${2:?arch}; VMLINUX=${3:?vmlinux dir}; SCX=${4:?scx include}; shift 4
INC=(-I"$VMLINUX" -I"$SCX" -I"$SCX/bpf-compat")
for d in "$@"; do INC+=(-I"$d"); done
try() {  # try <body>  -> 0 if it compiles
  printf '#include <scx/common.bpf.h>\nvoid probe(void){ %s }\n' "$1" |
    "$CLANG" -O2 -mcpu=v3 -target bpf -D__TARGET_ARCH_"$ARCH" "${INC[@]}" -fsyntax-only -x c - >/dev/null 2>&1
}
echo "/* generated by tools/probe-scx-abi.sh - do not edit */"
if try 'scx_bpf_dsq_move_to_local(0, 0);'; then
  echo "#define CND_MOVE_TO_LOCAL_2ARG 1"
elif try 'scx_bpf_dsq_move_to_local(0);'; then
  echo "/* scx_bpf_dsq_move_to_local: 1 argument */"
else
  echo "/* scx_bpf_dsq_move_to_local: probe failed, headers may be incompatible */"
fi
